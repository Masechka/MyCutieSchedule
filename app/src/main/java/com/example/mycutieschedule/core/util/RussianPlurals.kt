package com.example.mycutieschedule.core.util

/**
 * Утилиты для корректного склонения русских существительных
 * в зависимости от числительного.
 *
 * Русский язык использует три формы склонения после числительных:
 *   - **one**   — 1, 21, 31, … (но не 11)
 *   - **few**   — 2-4, 22-24, … (но не 12-14)
 *   - **many**  — 0, 5-20, 25-30, 40-50 …
 *
 * Эти функции вынесены сюда, чтобы избежать дублирования логики выбора
 * формы по всему UI (раньше один и тот же `eventCountWord` копировался
 * в `SharedSchedulesScreen` и `SharedScheduleDetailsScreen`).
 */

/**
 * Возвращает корректную форму существительного для указанного числа.
 *
 * Пример: `pluralRu(2, "событие", "события", "событий")` → `"события"`.
 *
 * @param count количество (любое неотрицательное целое)
 * @param one форма для 1 / 21 / 31 / …
 * @param few форма для 2-4 / 22-24 / …
 * @param many форма для 0 / 5-20 / 25-30 / …
 */
fun pluralRu(count: Int, one: String, few: String, many: String): String {
    val mod100 = count % 100
    // Числа 11..14 — особый случай, всегда форма "many"
    if (mod100 in 11..14) return many
    return when (count % 10) {
        1       -> one
        2, 3, 4 -> few
        else    -> many
    }
}

/**
 * Удобная обёртка для слова «событие» — самое частое использование
 * в этом приложении (карточки расписаний, бейджи импорта и т.п.).
 *
 * 1 → "событие"
 * 2-4, 22-24 … → "события"
 * 0, 5-20, 25-30, … → "событий"
 */
fun eventCountWordRu(count: Int): String =
    pluralRu(count, one = "событие", few = "события", many = "событий")
